/** Tiny in-memory limiter for write endpoints (per server instance). */
const hits = new Map<string, number[]>();

export function rateLimited(req: Request, bucket: string, max = 30, windowMs = 60_000) {
  const ip = req.headers.get("x-forwarded-for")?.split(",")[0]?.trim() || "local";
  const key = `${bucket}:${ip}`;
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  recent.push(now);
  hits.set(key, recent);
  return recent.length > max;
}
